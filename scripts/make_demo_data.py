def daterange():
    return [WINDOW_START + dt.timedelta(days=i) for i in range(WINDOW_DAYS)]


def busy_dates(rng):
    base = rng.uniform(0.30, 0.50)
    dec = rng.uniform(0.70, 0.80)
    out = []
    for d in daterange():
        p = dec if d.month == 12 else base
        if d.weekday() >= 5:
            p = min(0.97, p * 1.45)
        else:
            p *= 0.8
        if rng.random() < p:
            out.append(d.isoformat())
    return out


def name_for(cat, rng, used):
    while True:
        if cat in ("Банкетный зал", "Отель"):
            n = f"{'Отель' if cat == 'Отель' else 'Зал'} «{rng.choice(VENUE)}»"
        elif cat in ("Кейтеринг", "Декоратор", "Подарки и сувениры", "Фото и видеобудки", "Кавер-группа"):
            n = f"Студия «{rng.choice(VENUE)} {rng.randint(1, 9)}»"
        else:
            n = f"{rng.choice(FIRST)} {rng.choice(LAST)}"
        if n not in used:
            used.add(n)
            return n


def main():
    rng = random.Random(SEED)
    rows, used, used_details = [], set(), set()
    idx = 1
    for cat, (count, (pmin, pmax), hours) in CATEGORIES.items():
        for i in range(count):
            city = RARE_CITIES[cat][i] if cat in RARE_CITIES else rng.choices(
                ["Алматы", "Астана", "Зарубежье"], weights=[55, 40, 5])[0]
            k = rng.randint(2, 5)
            formats = sorted(rng.sample(FORMATS, k), key=FORMATS.index)
            langs = ["русский"]
            if rng.random() < 0.6:
                langs.append("казахский")
            if rng.random() < 0.25:
                langs.append("английский")
            price = round(rng.uniform(pmin, pmax) / 10_000) * 10_000
            max_h = rng.randint(*hours) if hours else None
            years = rng.randint(2, 15)
            role = ROLE[cat]
            parts = []
            for f in rng.sample(formats, min(2, len(formats))):
                options = [d for d in F_DETAIL[f] if (cat, f, d) not in used_details] or F_DETAIL[f]
                d = rng.choice(options)
                used_details.add((cat, f, d))
                parts.append(f"{ROLE_VERB[role](f)} — {d}")
            parts.append(rng.choice(ROLE_EXTRA[role]))
            for lng in langs[1:]:
                parts.append(LANG_PHRASES[lng])
            parts.append(f"опыт {years} лет")
            desc = ". ".join(p[0].upper() + p[1:] for p in parts) + "."
            cats = [cat]
            if cat == "Фотограф" and rng.random() < 0.25:
                cats.append("Видеограф")
            rows.append({
                "id": f"demo-{idx:03d}",
                "anon_name": name_for(cat, rng, used),
                "categories": cats,
                "city": city,
                "price_from_kzt": price,
                "event_formats": formats,
                "languages": langs,
                "max_hours": max_h,
                "busy_dates": busy_dates(rng),
                "description": desc,
                "synthetic": True,
                "city_imputed": False,
                "price_imputed": rng.random() < 0.1,
            })
            idx += 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"{len(rows)} профилей -> {OUT}")


if __name__ == "__main__":
    main()
